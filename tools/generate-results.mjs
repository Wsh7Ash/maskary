// Regenerates the committed artifacts in results/ by running the real
// pipeline over examples/. Run from the project root:
//
//   node tools/generate-results.mjs
//
// No network, no dependencies. Every byte written here comes from src/.

import { readFile, writeFile } from 'node:fs/promises';
import { detect } from '../src/detectors.js';
import { redact } from '../src/redact.js';
import { redactJsonText } from '../src/jsonredact.js';

const root = new URL('../', import.meta.url);

const read = (p) => readFile(new URL(p, root), 'utf8');
const write = (p, content) => writeFile(new URL(p, root), content, 'utf8');

const TYPE_ORDER = ['email', 'phone', 'ipv4', 'ipv6', 'credit_card', 'iban', 'url_cred', 'token', 'custom'];

// 1) plain text redaction: examples/sample.txt -> results/sample-redacted.txt
const txt = await read('examples/sample.txt');
const redactedTxt = redact(txt);
await write('results/sample-redacted.txt', redactedTxt.text);

// 2) structural JSON redaction: examples/sample.json -> results/sample-redacted.json
const json = await read('examples/sample.json');
const redactedJson = redactJsonText(json);
await write('results/sample-redacted.json', redactedJson.text + '\n');

// 3) detector report: per-type counts for both inputs -> results/detector-report.txt
const lines = [];
lines.push('maskary detector report');
lines.push('generated by: node tools/generate-results.mjs (runs src/detectors.js, no network)');
lines.push('');

function report(label, matches) {
  const total = matches.length;
  const distinct = new Set(matches.map((m) => `${m.type}\u0000${m.value}`)).size;
  lines.push(`source: ${label}`);
  lines.push(`  detected matches: ${total}   distinct values: ${distinct}`);
  lines.push('  (pre-overlap: a match nested inside a larger one is detected but not replaced)');
  lines.push('');
  lines.push('  type           occurrences   distinct');
  lines.push('  -------------  -----------   --------');
  for (const type of TYPE_ORDER) {
    const of = matches.filter((m) => m.type === type);
    if (of.length === 0) continue;
    const d = new Set(of.map((m) => m.value)).size;
    lines.push(`  ${type.padEnd(13)}  ${String(of.length).padStart(11)}   ${String(d).padStart(8)}`);
  }
  const covered = new Set(matches.map((m) => m.type));
  for (const type of TYPE_ORDER) {
    if (!covered.has(type)) lines.push(`  ${type.padEnd(13)}  ${String(0).padStart(11)}   ${String(0).padStart(8)}`);
  }
  lines.push('');
}

report('examples/sample.txt', detect(txt));
report('examples/sample.json (string values)', redactedJson.matches);
report('examples/sample.csv', detect(await read('examples/sample.csv')));

lines.push('replaced occurrences (after longest-first overlap resolution, default policies):');
lines.push(`  sample.txt   ${JSON.stringify(redactedTxt.counts)}`);
lines.push(`  sample.json  ${JSON.stringify(redactedJson.counts)}`);
lines.push('');
lines.push('NOTE: examples contain synthetic data only (RFC 2606 domains, 555 ranges).');
lines.push('');

await write('results/detector-report.txt', lines.join('\n'));

console.log('wrote results/sample-redacted.txt');
console.log('wrote results/sample-redacted.json');
console.log('wrote results/detector-report.txt');
console.log(`sample.txt counts: ${JSON.stringify(redactedTxt.counts)}`);
console.log(`sample.json counts: ${JSON.stringify(redactedJson.counts)}`);
